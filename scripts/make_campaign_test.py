"""Assembles campaigns.rs from the shared harness in engbounty.rs plus scripts/campaigns_tail.rs.txt."""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "engbounty.rs").read_text(encoding="utf-8")
start = src.index("// ---- DAG-CBOR builder")
end = src.index("#[test]")
body = src[start:end]

# The harness needs key rotation and a settable commit time.
for old, new in [
    ("struct Account { did: String, ops: Vec<Vec<u8>>, repo_key: SigningKey }",
     "struct Account { did: String, ops: Vec<Vec<u8>>, repo_key: SigningKey, rotation_key: SigningKey, rev: u64 }"),
    ("Self { did, ops: vec![genesis], repo_key }",
     "Self { did, ops: vec![genesis], repo_key, rotation_key, rev: T0 }"),
    ('("rev", V::T(tid(T0)))', '("rev", V::T(tid(self.rev)))'),
    ("    /// Build a proof that `record` sits at",
     "    fn rotate(&mut self) {\n"
     "        let repo_key = SigningKey::random(&mut rand_core::OsRng);\n"
     "        let op = plc_op(Some(self.ops.last().unwrap()), &self.rotation_key, &repo_key, &self.rotation_key);\n"
     "        self.ops.push(op);\n"
     "        self.repo_key = repo_key;\n"
     "    }\n"
     "    /// Build a proof that `record` sits at"),
]:
    assert old in body, old
    body = body.replace(old, new)

head = """//   SPDX-License-Identifier: BSD-3-Clause
//! End-to-end tests of Campaign: rules, payout binding, vouches, allocations, rounds, referrals, linked claims,
//! the funder's limits, receipts and cost. Generated by scripts/make_campaign_test.py; edit the tail file there.

use k256::ecdsa::{SigningKey, signature::Signer as _};
use sha2::{Digest, Sha256};
use tari_crypto::{keys::PublicKey as _, ristretto::{RistrettoPublicKey, RistrettoSecretKey}, tari_utilities::ByteArray};
use tari_engine_types::virtual_substate::{VirtualSubstate, VirtualSubstateId};
use tari_ootle_common_types::substate_type::SubstateType;
use tari_ootle_transaction::args;
use tari_template_lib::types::{Amount, ComponentAddress, NonFungibleAddress, ResourceAddress, bytes::Bytes, constants::TARI_TOKEN, crypto::RistrettoPublicKeyBytes};
use tari_template_test_tooling::TemplateTest;

const CRATE_PATH: &str = env!("CARGO_MANIFEST_DIR");
const CAMPAIGN: &str = "tests/templates/campaigns";
const LINK: &str = "tests/templates/link-registry";

"""
tail = (root / "scripts" / "campaigns_tail.rs.txt").read_text(encoding="utf-8")
(root / "campaigns.rs").write_text(head + body + tail, encoding="utf-8", newline="\n")
print("wrote campaigns.rs")
