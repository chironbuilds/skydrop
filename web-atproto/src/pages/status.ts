export function statusPage(): Page {
  const live = h("div", null, pill("plain", "Checking…"));
  (async () => {
    try {
      const r = await fetch(`${DEPLOYMENT.indexer}/health`, { signal: AbortSignal.timeout(8000) });
      if (!r.ok) throw new Error(String(r.status));
      const j = (await r.json()) as { current_epoch?: number; version?: string; status?: string };
      replace(live, pill(j.status === "ok" ? "ok" : "warn", j.status === "ok" ? "Network responding" : `Status: ${j.status}`), h("p", { class: "muted small-text", style: "margin-top:8px" }, `Indexer version ${j.version ?? "unknown"}, epoch ${j.current_epoch?.toLocaleString("en-US") ?? "unknown"}.`));
    } catch {
      replace(live, pill("warn", "Couldn't reach the network"), h("p", { class: "muted small-text", style: "margin-top:8px" }, "The indexer may be down or may not allow requests from this site."));
    }
  })();

  const total = TESTS.reduce((n, t) => n + t.passed, 0);
  return {
    title: "Status",
    body: h("div", { class: "wrap narrow" },
      pageHead("Status", "Where things actually stand", "What's built, what's tested, what's deployed and what isn't. Updated by hand with each release."),
      h("div", { class: "grid g3", style: "margin-top:0" },
        h("div", { class: "card" }, h("span", { class: "tag" }, "contracts"), h("h3", null, contractsOnNetwork() ? "Published" : "Not published"), h("p", null, contractsOnNetwork() ? (isPublished() ? `Live on the ${DEPLOYMENT.network}.` : `On the ${DEPLOYMENT.network}. Funding and claiming from the site is still being built.`) : `Built and tested against Ootle ${DEPLOYMENT.ootle}. Nothing is on the network since its reset.`)),
        h("div", { class: "card" }, h("span", { class: "tag" }, "tests"), h("h3", null, `${total} passing`), h("p", null, `Run on ${TESTED_AT}. Every deliberately broken safety check was caught: 26 in Campaign, 14 in the Escrow and 18 in the LinkRegistry.`)),
        h("div", { class: "card" }, h("span", { class: "tag" }, DEPLOYMENT.network.toLowerCase()), live),
      ),
      h("div", { class: "note warn" }, h("strong", null, "Testnet only. "), "No third-party audit yet. Internal reviews found and fixed real bugs, so expect there are more. Don't put real value behind this yet."),

      h("h2", { class: "big", style: "margin-top:40px" }, "Tests"),
      h("p", { class: "muted", style: "margin-top:8px" }, "Engine tests run each contract in the real Ootle engine, with accounts and signatures generated by the test."),
      h("div", { class: "tablewrap" }, h("table", null,
        h("thead", null, h("tr", null, h("th", null, "Suite"), h("th", null, "Covers"), h("th", { style: "text-align:right" }, "Passed"))),
        h("tbody", null, TESTS.map((t) => h("tr", null, h("td", { class: "m" }, t.name), h("td", { class: "muted" }, t.covers), h("td", { class: "num" }, `${t.passed}/${t.passed}`)))),
      )),

      h("h2", { class: "big", style: "margin-top:40px" }, "What a claim costs"),
      h("p", { class: "muted", style: "margin-top:8px" }, "Measured in the engine on 0.49.2 with one-operation identity logs and common keys. The limit is 250M points per transaction."),
      h("div", { class: "tablewrap" }, h("table", null,
        h("thead", null, h("tr", null, h("th", null, "Claim"), h("th", { style: "text-align:right" }, "WASM points"), h("th", { style: "text-align:right" }, "Share of limit"))),
        h("tbody", null, [["One rule", "21.2M", "8%"], ["Three rules", "34.8M", "14%"], ["Eight rules, two vouches", "83.6M", "33%"]].map(([a, b, c]) => h("tr", null, h("td", null, a), h("td", { class: "num" }, b), h("td", { class: "num" }, c)))),
      )),

      h("h2", { class: "big", style: "margin-top:40px" }, "Deployed addresses"),
      contractsOnNetwork()
        ? h("div", { class: "tablewrap" }, h("table", null, h("tbody", null, [["Campaign template", DEPLOYMENT.campaignTemplate], ["LinkRegistry", DEPLOYMENT.linkRegistry], ["Verifier", DEPLOYMENT.verifier]].map(([a, b]) => h("tr", null, h("td", null, a), h("td", { class: "m" }, b))))))
        : h("p", { class: "muted", style: "margin-top:8px" }, "None on the current network. Addresses from before the 0.49 reset no longer exist."),

      h("h2", { class: "big", style: "margin-top:40px" }, "Roadmap"),
      h("div", { class: "tablewrap" }, h("table", null, h("tbody", null, ROADMAP.map(([name, state, text]) => h("tr", null, h("td", { style: "white-space:nowrap" }, pill(state === "done" ? "ok" : state === "next" ? "info" : "plain", state === "done" ? "Done" : state === "next" ? "Next" : "Later")), h("td", null, h("strong", null, name), h("div", { class: "muted small-text" }, text))))))),
      h("div", { class: "spacer" }),
    ),
  };
}
